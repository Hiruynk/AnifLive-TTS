
const {chromium}=require("playwright");const fs=require("fs");const assert=require("node:assert/strict");
(async()=>{const browser=await chromium.launch({headless:true,args:["--disable-gpu"]});
const page=await browser.newPage({viewport:{width:1440,height:900},reducedMotion:"no-preference",locale:"en-US"});
const fixtureResponse = await page.goto((process.env.STUDIO_QA_BASE || "http://host.docker.internal:9893") + "/#settings",{waitUntil:"networkidle"}); assert.equal(fixtureResponse.headers()["x-aniflive-ui-fixture"],"synthetic");
const d=page.locator('[data-ux-disclosure="workstationAdvanced"]');const s=d.locator("summary");
const support=await page.evaluate(()=>CSS.supports("selector(details::details-content)")&&CSS.supports("interpolate-size","allow-keywords"));
assert.ok(support);
const initial=await d.evaluate(e=>e.getBoundingClientRect().height);
await s.click();await page.waitForTimeout(70);const middle=await d.evaluate(e=>e.getBoundingClientRect().height);
await page.waitForTimeout(240);const expanded=await d.evaluate(e=>e.getBoundingClientRect().height);
assert.ok(middle>initial&&middle<expanded,{initial,middle,expanded});
await s.click();await page.waitForTimeout(50);await s.click();await page.waitForTimeout(50);await s.click();await page.waitForTimeout(280);
assert.equal(await d.evaluate(e=>e.open),false);assert.ok(Math.abs(await d.evaluate(e=>e.getBoundingClientRect().height)-initial)<2);
await page.locator("#studioLocaleButton").click();await page.waitForTimeout(60);
const opening=await page.locator("#studioLocaleMenu").evaluate(e=>Number(getComputedStyle(e).opacity));assert.ok(opening>0&&opening<1);
await page.waitForTimeout(220);await page.keyboard.press("Escape");await page.waitForTimeout(50);
const closing=await page.locator("#studioLocaleMenu").evaluate(e=>({display:getComputedStyle(e).display,opacity:Number(getComputedStyle(e).opacity)}));
assert.notEqual(closing.display,"none");assert.ok(closing.opacity<1);
await page.waitForTimeout(220);
await page.locator('#moduleNav [data-view="training"]').click();await page.locator('[data-view-panel="training"] [data-open-project]').click();
const fields=await page.locator('.studio-path-picker input,.studio-path-picker textarea').evaluateAll(els=>els.map(e=>({id:e.id,background:getComputedStyle(e).backgroundColor})));
assert.ok(fields.length>0);assert.ok(fields.every(e=>e.background==="rgba(0, 0, 0, 0)"));
await page.screenshot({path:"/qa/shots/path-picker-material.png"});
await page.keyboard.press("Escape");
await page.emulateMedia({reducedMotion:"reduce"});
await page.locator('#moduleNav [data-view="settings"]').click();
const reduced=await d.evaluate(e=>getComputedStyle(e,"::details-content").transitionDuration);
assert.equal(reduced,"0s");
const result={support,disclosure:{initial,middle,expanded,reversal:"passed"},dropdown:{opening,closing},pathFields:fields,reducedMotion:reduced};
fs.writeFileSync("/qa/motion-material-results.json",JSON.stringify(result,null,2));console.log(JSON.stringify(result));await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
